"""Produce the LLMJudge reference fixture from a given ragnarok-ai version.

The fixture records, for both prompt formats and the four criteria, the exact
prompt sent to a scripted LLM and the result returned, with and without
medical mode. It must be generated by running the *reference* version of the
library (tag v1.12.3), never the code under test:

    PYTHONPATH=<checkout of v1.12.3>/src python tests/unit/evaluators/fixtures/make_judge_reference.py \
        --commit <sha of the checkout> > tests/unit/evaluators/fixtures/judge_reference_v1_12_3.json

The regression test replays the same calls against the current code and
requires identical prompts and results.
"""

from __future__ import annotations

import argparse
import asyncio
import dataclasses
import json
import sys
from typing import Any

import ragnarok_ai
from ragnarok_ai.evaluators.judge import LLMJudge

CRITERIA = ("faithfulness", "relevance", "hallucination", "completeness")

# One raw score per criterion so the fixture covers PASS, PARTIAL and FAIL
RAW_SCORES = {"faithfulness": 5, "relevance": 3, "hallucination": 2, "completeness": 4}
EXPLANATIONS = {
    "faithfulness": "Every claim is supported by the context.",
    "relevance": "The answer addresses part of the question only.",
    "hallucination": "Two details are not in the context.",
    "completeness": "Most of the relevant information is covered.",
}

PLAIN_INPUTS = {
    "question": "What is the default restart policy of a Docker container?",
    "context": "Docker containers use the `no` restart policy by default.\n\n---\n\nUse `--restart` to change it.",
    "answer": "By default, a container is not restarted (policy `no`).",
}

MEDICAL_INPUTS = {
    "question": "What condition does the pt have and what was prescribed?",
    "context": "Pt diagnosed with CHF. BP 140/90. Prescribed ACE inhibitor, follow-up in 2 wk.",
    "answer": "The patient has CHF and was given an ACE inhibitor; BP was 140/90.",
}

MODELS = {"prometheus": "prometheus2:latest", "score-n": "mistral:7b"}


def scripted_response(fmt: str, criterion: str, raw_score: int) -> str:
    """What the fake LLM answers, in the format the prompt asks for."""
    explanation = EXPLANATIONS[criterion]
    if fmt == "prometheus":
        return f"{explanation} [RESULT] {raw_score}"
    verdict = "PASS" if raw_score >= 4 else ("FAIL" if raw_score <= 2 else "PARTIAL")
    return f"Score: {raw_score}\nVerdict: {verdict}\nExplanation: {explanation}"


class FakeLLM:
    """Scripted LLM: returns the configured text per call and records every prompt."""

    def __init__(self, model: str, responses: list[str]) -> None:
        self.model = model
        self._responses = list(responses)
        self.prompts: list[str] = []

    async def generate(self, prompt: str) -> str:
        self.prompts.append(prompt)
        return self._responses.pop(0)

    async def embed(self, text: str) -> list[float]:  # noqa: ARG002
        return [0.0]


def result_to_dict(result: Any) -> dict[str, Any]:
    """Only the fields that exist in every version (new optional fields are ignored)."""
    data = dataclasses.asdict(result)
    return {k: data[k] for k in ("verdict", "score", "explanation", "criteria", "raw_score")}


def call(judge: LLMJudge, criterion: str, inputs: dict[str, str]) -> Any:
    if criterion == "faithfulness":
        return judge.evaluate_faithfulness(
            context=inputs["context"], question=inputs["question"], answer=inputs["answer"]
        )
    if criterion == "relevance":
        return judge.evaluate_relevance(question=inputs["question"], answer=inputs["answer"])
    if criterion == "hallucination":
        return judge.detect_hallucination(context=inputs["context"], answer=inputs["answer"])
    return judge.evaluate_completeness(question=inputs["question"], answer=inputs["answer"], context=inputs["context"])


async def one_case(fmt: str, medical_mode: bool, inputs: dict[str, str]) -> dict[str, Any]:
    case: dict[str, Any] = {
        "format": fmt,
        "model": MODELS[fmt],
        "medical_mode": medical_mode,
        "inputs": inputs,
        "criteria": {},
    }
    for criterion in CRITERIA:
        llm = FakeLLM(MODELS[fmt], [scripted_response(fmt, criterion, RAW_SCORES[criterion])])
        judge = LLMJudge(llm=llm, medical_mode=medical_mode)
        result = await call(judge, criterion, inputs)
        case["criteria"][criterion] = {
            "response": scripted_response(fmt, criterion, RAW_SCORES[criterion]),
            "prompt": llm.prompts[0],
            "result": result_to_dict(result),
        }
    # evaluate_all: four calls in a fixed order, and the combined serialization
    llm = FakeLLM(MODELS[fmt], [scripted_response(fmt, c, RAW_SCORES[c]) for c in CRITERIA])
    judge = LLMJudge(llm=llm, medical_mode=medical_mode)
    results = await judge.evaluate_all(context=inputs["context"], question=inputs["question"], answer=inputs["answer"])
    case["evaluate_all"] = {"prompts": list(llm.prompts), "to_dict": results.to_dict()}
    # unparseable output: the exception class and message
    unparseable = "I think the answer is fine overall." if fmt == "score-n" else "The response is acceptable."
    llm = FakeLLM(MODELS[fmt], [unparseable])
    judge = LLMJudge(llm=llm, medical_mode=medical_mode)
    try:
        await call(judge, "faithfulness", inputs)
    except Exception as exc:
        case["unparseable"] = {"response": unparseable, "exception": type(exc).__name__, "message": str(exc)}
    else:
        case["unparseable"] = {"response": unparseable, "exception": None, "message": None}
    return case


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", required=True, help="full SHA of the checkout the fixture is produced from")
    args = ap.parse_args()
    # The checkout actually loaded is reported to the operator only; the fixture
    # identifies the reference by version and commit SHA, never by a local path.
    print(f"reference module: {ragnarok_ai.__file__} (version {ragnarok_ai.__version__})", file=sys.stderr)
    fixture = {
        "reference": {
            "ragnarok_ai_version": ragnarok_ai.__version__,
            "commit": args.commit,
            "generator": "tests/unit/evaluators/fixtures/make_judge_reference.py",
        },
        "cases": [
            await one_case("prometheus", False, PLAIN_INPUTS),
            await one_case("score-n", False, PLAIN_INPUTS),
            await one_case("prometheus", True, MEDICAL_INPUTS),
            await one_case("score-n", True, MEDICAL_INPUTS),
        ],
    }
    json.dump(fixture, sys.stdout, indent=2, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    asyncio.run(main())
